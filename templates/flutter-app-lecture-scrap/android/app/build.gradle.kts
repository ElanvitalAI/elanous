    id("dev.flutter.flutter-gradle-plugin")
}

val releaseStoreFile = System.getenv("ELANOUS_ANDROID_KEYSTORE")
val releaseStorePassword = System.getenv("ELANOUS_ANDROID_KEYSTORE_PASSWORD")
val releaseKeyAlias = System.getenv("ELANOUS_ANDROID_KEY_ALIAS")
val releaseKeyPassword = System.getenv("ELANOUS_ANDROID_KEY_PASSWORD")
val hasReleaseSigning = listOf(
    releaseStoreFile,
    releaseStorePassword,
    releaseKeyAlias,
    releaseKeyPassword,
).all { !it.isNullOrBlank() }
val isReleaseTask = gradle.startParameter.taskNames.any {
    it.contains("release", ignoreCase = true)
}
if (isReleaseTask && !hasReleaseSigning) {
    throw GradleException(
        "Release builds require ELANOUS_ANDROID_KEYSTORE, " +
            "ELANOUS_ANDROID_KEYSTORE_PASSWORD, ELANOUS_ANDROID_KEY_ALIAS, " +
            "and ELANOUS_ANDROID_KEY_PASSWORD."
    )
}

