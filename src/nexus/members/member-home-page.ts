/** A80 member home: the server supplies public metadata, never a saved key value. */
export interface MemberHomePageInput {
  readonly name: string;
  readonly email: string;
  readonly publicId: string;
  readonly referralUrl: string;
  readonly membership: { readonly label: string; readonly note: string };
  /** `recheckUrl` reloads this home when the connection lookup failed. */
  readonly connection: {
    readonly linked: boolean | null;
    readonly recheckUrl: string;
  };
  /** The brand link: the public site home. */
  readonly siteUrl: string;
  /** Chat address served by the connected device (app host); shown only when a device is connected and a handle exists. */
  readonly webChatUrl?: string;
  /** The member's handle address when a handle exists (shown as text: the relay does not serve it yet). */
  readonly myElanous?: { readonly handleAddress: string | null };
  /** The website's handle step («가입 2/2»): a member without a handle sets it there (that write keeps the website origin). */
  readonly handleStepUrl: string;
  readonly devices:
    | readonly {
        readonly name: string;
        readonly kind: string;
        readonly lastUsed: string;
      }[]
    | null;
  /** The member's current app name; null when no app slot exists yet. */
  readonly appName?: {
    readonly slug: string | null;
    /** The lookup failed: do not offer to choose or change a name. */ readonly unknown?: true;
    /** No slot and no event code: an app address opens only for members who joined with an event code (OP 11-18 B). */
    readonly needsEventCode?: true;
  };
  /** Per-response CSP nonce generated by the route owner. */
  readonly nonce: string;
}

function html(value: string): string {
  return value.replace(
    /[&<>"']/g,
    (character) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[character]!,
  );
}

function href(value: string): string {
  try {
    const url = new URL(value, "https://elanous.ai");
    if (url.protocol !== "https:" && url.protocol !== "http:") return "#";
    return html(value);
  } catch {
    return "#";
  }
}

