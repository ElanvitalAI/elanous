/** Fault device for a push accepted by the remote whose client reports a timeout. */
export function gitPushTimeoutAfterRemoteApplyShim(): string {
  return [
    '#!/bin/sh',
    'if [ "$1" = "push" ]; then',
    '  if [ "$ELANOUS_SIM_PUSH_TIMEOUT_MODE" = "move-source-then-apply" ]; then',
    '    "$ELANOUS_SIM_REAL_GIT" -c user.name=Simulator -c user.email=simulator@example.test commit --allow-empty -m "move source during push" >/dev/null',
    '    "$ELANOUS_SIM_REAL_GIT" "$@" || exit $?',
    '    printf "%s\\n" "simulated transport timeout after ref moved and remote accepted push" >&2',
    '    exit 1',
    '  fi',
    '  if [ "$ELANOUS_SIM_PUSH_TIMEOUT_MODE" = "before-apply-ref-cycle" ]; then',
    '    "$ELANOUS_SIM_REAL_GIT" update-ref -d "$ELANOUS_SIM_PUSH_SOURCE_REF"',
    '    "$ELANOUS_SIM_REAL_GIT" symbolic-ref "$ELANOUS_SIM_PUSH_SOURCE_REF" "$ELANOUS_SIM_PUSH_SYMBOLIC_TARGET"',
    '    "$ELANOUS_SIM_REAL_GIT" symbolic-ref --delete "$ELANOUS_SIM_PUSH_SOURCE_REF"',
    '    "$ELANOUS_SIM_REAL_GIT" update-ref "$ELANOUS_SIM_PUSH_SOURCE_REF" "$ELANOUS_SIM_PUSH_RESTORE_SHA"',
    '    printf "%s\\n" "simulated transport timeout after source ref changed through symbolic form" >&2',
    '    exit 1',
    '  fi',
    '  if [ "$ELANOUS_SIM_PUSH_TIMEOUT_MODE" = "before-apply-restore-head" ]; then',
    '    "$ELANOUS_SIM_REAL_GIT" -c user.name=Simulator -c user.email=simulator@example.test commit --allow-empty -m "move source away" >/dev/null',
    '    "$ELANOUS_SIM_REAL_GIT" reset --hard "$ELANOUS_SIM_PUSH_RESTORE_SHA" >/dev/null',
    '    printf "%s\\n" "simulated transport timeout after source ref moved away and back" >&2',
    '    exit 1',
    '  fi',
    '  if [ "$ELANOUS_SIM_PUSH_TIMEOUT_MODE" = "before-apply-move-head" ]; then',
    '    "$ELANOUS_SIM_REAL_GIT" -c user.name=Simulator -c user.email=simulator@example.test commit --allow-empty -m "move source before push" >/dev/null',
    '    printf "%s\\n" "simulated transport timeout after source ref moved before push" >&2',
    '    exit 1',
    '  fi',
    '  if [ "$ELANOUS_SIM_PUSH_TIMEOUT_MODE" = "before-apply" ]; then',
    '    printf "%s\\n" "simulated transport timeout before remote accepted push" >&2',
    '    exit 1',
    '  fi',
    '  "$ELANOUS_SIM_REAL_GIT" "$@"',
    '  push_status=$?',
    '  if [ "$push_status" -ne 0 ]; then exit "$push_status"; fi',
    '  printf "%s\\n" "simulated transport timeout after remote accepted push" >&2',
    '  exit 1',
    'fi',
    'if [ "$1" = "ls-remote" ]; then printf "%s\\n" "$*" >> "$ELANOUS_SIM_GIT_LS_REMOTE_CALLS"; fi',
    'exec "$ELANOUS_SIM_REAL_GIT" "$@"',
    '',
  ].join('\n');
}
